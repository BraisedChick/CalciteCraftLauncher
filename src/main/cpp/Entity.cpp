EntityType entityTypeFromProtocolId(int typeId) {
    // 有效范围：0 ~ static_cast<int>(EntityType::FISHING_BOBBER)
    if (typeId >= 0 && typeId <= static_cast<int>(EntityType::FISHING_BOBBER)) {
        return static_cast<EntityType>(typeId);
    }
    return EntityType::UNKNOWN;
}
